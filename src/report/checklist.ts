import type { ChecklistReport, ChecklistResult, ItemStatus } from "../checklist/index.js";
import { table } from "./text.js";

const MARK: Record<ItemStatus, string> = { done: "done", partial: "partial", missing: "missing", na: "n/a", unanswered: "—" };
const BOX: Record<ItemStatus, string> = { done: "[x]", partial: "[~]", missing: "[ ]", na: "[-]", unanswered: "[?]" };

const pct = (n: number | null): string => (n === null ? "—" : `${Math.round(n * 100)}%`);
const how = (i: ChecklistResult): string => (i.source === "measured" ? "scan" : i.source === "answered" ? "team" : i.source === "overridden" ? "team (over scan)" : "");

/** The terminal summary: a score per area, then every item the scan measured, with its evidence. */
export function formatChecklist(report: ChecklistReport): string {
  const s = report.summary;
  const out: string[] = [];
  out.push(`dsa checklist — ${report.system} — ${pct(s.score)} of applicable items (${s.measured} measured by the scan, ${s.answered} answered, ${s.unanswered} unanswered)`);
  out.push("");
  out.push(
    table(
      ["area", "score", "done", "partial", "missing", "unanswered"],
      report.areas.map((a) => [a.title, pct(a.score), String(a.done), String(a.partial), String(a.missing), String(a.unanswered)]),
      ["left", "right", "right", "right", "right", "right"],
    ),
  );
  for (const area of report.areas) {
    const items = report.items.filter((i) => i.area === area.id && i.source !== "none");
    if (!items.length) continue;
    out.push("");
    out.push(area.title);
    for (const i of items) {
      out.push(`  ${MARK[i.status].padEnd(8)} ${i.title}  (${how(i)})`);
      for (const e of i.evidence) out.push(`             ${e}`);
      if (i.measured) out.push(`             scan said ${i.measured.status}: ${i.measured.evidence[0] ?? ""}`);
    }
  }
  if (s.unanswered) {
    out.push("");
    out.push(`${s.unanswered} items need the team's answer. Add them to dsa.checklist.json: { "items": { "<id>": { "status": "done" } } }`);
    out.push(`ids: ${report.items.filter((i) => i.status === "unanswered").map((i) => i.id).join(", ")}`);
  }
  if (report.unknownAnswers.length) {
    out.push("");
    out.push(`unknown ids in ${report.answersPath}: ${report.unknownAnswers.join(", ")}`);
  }
  return out.join("\n");
}

/** The checklist as a Markdown page to share: one table per area, ids included so answers can be filed. */
export function checklistMarkdown(report: ChecklistReport): string {
  const s = report.summary;
  const out: string[] = [
    `# Design system checklist — ${report.system}`,
    "",
    `Generated by dsa ${report.meta.dsaVersion} on ${report.meta.generatedAt.slice(0, 10)}.`,
    `Score: **${pct(s.score)}** of applicable items. ${s.measured} items were measured by the scan, ${s.answered} answered by the team, ${s.unanswered} still need an answer.`,
    "",
    "Key: `[x]` done · `[~]` partial · `[ ]` missing · `[-]` not applicable · `[?]` needs the team's answer. Partial counts as half.",
    "",
    "| Area | Score | Done | Partial | Missing | Unanswered |",
    "|---|---:|---:|---:|---:|---:|",
    ...report.areas.map((a) => `| ${a.title} | ${pct(a.score)} | ${a.done} | ${a.partial} | ${a.missing} | ${a.unanswered} |`),
  ];
  for (const area of report.areas) {
    out.push("", `## ${area.title} — ${pct(area.score)}`, "", "| | Item | Size | How | Evidence |", "|---|---|---|---|---|");
    for (const i of report.items.filter((x) => x.area === area.id)) {
      const evidence = [...i.evidence, ...(i.measured ? [`scan said ${i.measured.status}`] : [])].map(cell).join("<br>");
      out.push(`| ${BOX[i.status]} | **${cell(i.title)}** \`${i.id}\`<br>${cell(i.about)} | ${i.size} | ${how(i) || "—"} | ${evidence || "—"} |`);
    }
  }
  return out.join("\n") + "\n";
}

function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\n/g, " ");
}
